public class VariablesyConstantes {

    public static void main(String[] args) {

        //variables

        String name = "Anderson";
        System.out.println(name);

        name = "Ana";
        System.out.println(name);

       // name = 37; NO SE PUEDE CAMBIAR EL TIPO DE VARIABLE

        int age = 21;
        System.out.println(age);

        var email = "holamundo@gamil.com";
        System.out.println(email);

        var year = 2026;
        System.out.println(year);

        // CONSTANTES

        final String EMAIL = "holamundo@gamil.com";
        // email = "jajaja@gmail.com";  ES UNA CONSTANTE Y NO SE PUEDE CAMBIAR.
        System.out.println(EMAIL);

    }
}
